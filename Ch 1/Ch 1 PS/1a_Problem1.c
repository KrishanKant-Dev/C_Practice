// Write a C program to calculate the area of a rectangle, using hard coded inputs

#include <stdio.h>

int main()
{
    int length = 78;
    int breadth = 80;
    int area = length*breadth;

    printf("============================\n");
    printf("The Length is: %d units",length);
    printf("\nThe Breadth is: %d units",breadth);
    printf("\nThe Area is: %d unit sq",area);
    printf("\n============================");

    return 0;
}